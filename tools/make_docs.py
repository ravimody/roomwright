"""Regenerate docs/TOOLS.md (every tool's docstring) and docs/DATA.md (the JSON Schemas as tables), so the reference
can't drift from the code. tests/test_docs.py fails when either is stale.

Usage (from the repo root):
  uv run tools/make_docs.py            write both files
  uv run tools/make_docs.py --check    exit 1 if either would change
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SKIP = {"roomframe.py", "blender_models.py", "measure_common.py", "sandbox_guard.py"}
GROUPS = [
    ("Set up and check", ["doctor", "new_room", "validate_room", "smoke_rooms", "make_docs"]),
    ("Align and map the scan", ["align_and_render", "map_room", "room_views", "detect_furniture", "sections", "region_sections",
                                "wall_profile", "corner_views", "ceiling_views", "ceiling_raycast", "ceiling_compare", "ceiling_side_by_side"]),
    ("Verify the model", ["geometry_check", "blender_scene", "scan_compare", "photo_match", "photo_compare", "color_match", "light_match"]),
    ("Layouts and planning", ["check_layout", "flow_plan", "speaker_plan"]),
    ("Render", ["render_photoreal", "render_batch", "render_modal", "photometry"]),
    ("Models and textures", ["model_import", "rug_from_scan", "rug_texture", "wallpaper_from_scan"]),
    ("Reports", ["build_report", "export_pdf", "screenshot"]),
]


def doc_of(p):
    s = p.read_text()
    if p.suffix == ".py":
        m = re.search(r'^"""(.*?)"""', s.split("# ///\n", 2)[-1], re.S | re.M)
        return m.group(1).strip() if m else ""
    lines = []
    for line in s.splitlines()[1 if s.startswith("#!") else 0:]:
        m = re.match(r"^\s*(?://|#)\s?(.*)$", line)
        if not m:
            break
        lines.append(m.group(1))
    return "\n".join(lines).strip()


def tools_md():
    tools = {p.stem: p for p in sorted((REPO / "tools").iterdir()) if p.suffix in (".py", ".mjs", ".sh") and p.name not in SKIP}
    seen, out = set(), ["# Tools", "", "Generated by `tools/make_docs.py` from each tool's docstring; edit the tool, not this file.",
                        "Run them from inside `rooms/<room>/` as `uv run ../../tools/<tool>.py …` (engine checkout) or `roomwright <tool> …` (installed).", ""]
    groups = [(g, [n for n in names if n in tools]) for g, names in GROUPS]
    rest = sorted(set(tools) - {n for _, names in groups for n in names})
    if rest:
        groups.append(("Other", rest))
    for g, names in groups:
        if not names:
            continue
        out += [f"## {g}", ""]
        for n in names:
            for p in sorted(q for q in tools.values() if q.stem == n):
                if p in seen:
                    continue
                seen.add(p)
                out += [f"### {p.name}", "", "```text", doc_of(p) or "(no docstring)", "```", ""]
    return "\n".join(out).rstrip() + "\n"


def type_name(v):
    if "oneOf" in v:
        return " or ".join(type_name(x) for x in v["oneOf"])
    if "enum" in v:
        return " \\| ".join(json.dumps(x) for x in v["enum"])
    t = v.get("type") or ("const" if "const" in v else "")
    if t == "array" and isinstance(v.get("items"), dict):
        it = v["items"]
        sub = type_name(it) if "oneOf" in it else it.get("type", "object")
        return f"array of {sub}" + (f"[{it['minItems']}]" if it.get("minItems") == it.get("maxItems") and it.get("minItems") else "")
    return t


def schema_rows(schema, defs, prefix=""):
    rows = []
    props = schema.get("properties", {})
    req = set(schema.get("required", []))
    for k, v in props.items():
        if "$ref" in v:
            v = defs.get(v["$ref"].split("/")[-1], v)
        t = type_name(v)
        desc = v.get("description", "")
        rows.append(f"| `{prefix}{k}` | {t} | {'yes' if k in req else ''} | {desc} |")
        sub = v.get("items") if v.get("type") == "array" else v
        if isinstance(sub, dict) and sub.get("properties"):
            rows += schema_rows(sub, defs, f"{prefix}{k}{'[]' if v.get('type') == 'array' else ''}.")
        elif isinstance(v.get("additionalProperties"), dict) and v["additionalProperties"].get("properties"):
            rows += schema_rows(v["additionalProperties"], defs, f"{prefix}{k}.<name>.")
        elif isinstance(v.get("additionalProperties"), dict) and "$ref" in v["additionalProperties"]:
            rows += schema_rows(defs[v["additionalProperties"]["$ref"].split("/")[-1]], defs, f"{prefix}{k}.<name>.")
    return rows


def data_md():
    out = ["# Data reference", "", "Generated by `tools/make_docs.py` from `schema/*.schema.json`; edit the schema, not this file.",
           "Check a room with `uv run ../../tools/validate_room.py` (schema plus consistency checks). Builder-specific catalog keys",
           "(sofa `arms`, lamp `shade`, …) are described in the household's `builders/README.md` and in docs/MODELING.md; any catalog key can be overridden per layout item.", ""]
    for name in ("room", "catalog", "layout", "render_sets", "build"):
        s = json.loads((REPO / "schema" / f"{name}.schema.json").read_text())
        out += [f"## {s.get('title', name)}", ""]
        if s.get("description"):
            out += [s["description"], ""]
        body = s
        if s.get("type") == "array":
            body = s["items"]
        elif name == "catalog":
            out += ["Top level: `items` maps an id to an item:", ""]
            body = s["properties"]["items"]["additionalProperties"]
        out += ["| key | type | required | notes |", "|---|---|---|---|", *schema_rows(body, s.get("$defs", {})), ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    stale = []
    for path, text in ((REPO / "docs/TOOLS.md", tools_md()), (REPO / "docs/DATA.md", data_md())):
        if not path.exists() or path.read_text() != text:
            stale.append(path.relative_to(REPO))
            if not a.check:
                path.parent.mkdir(exist_ok=True)
                path.write_text(text)
    if a.check and stale:
        sys.exit(f"stale: {', '.join(map(str, stale))} (run `uv run tools/make_docs.py`)")
    print("wrote " + ", ".join(map(str, stale)) if stale and not a.check else "docs up to date")


if __name__ == "__main__":
    main()
